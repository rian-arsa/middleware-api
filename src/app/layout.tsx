import type { Metadata } from "next";
import { Geist, Geist_Mono, Inter, Roboto, Plus_Jakarta_Sans, JetBrains_Mono, Fira_Code, Source_Code_Pro } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const inter = Inter({ variable: "--font-inter", subsets: ["latin"] });
const roboto = Roboto({ variable: "--font-roboto", subsets: ["latin"], weight: ["400", "500", "700"] });
const jakarta = Plus_Jakarta_Sans({ variable: "--font-jakarta", subsets: ["latin"] });
const jetbrains = JetBrains_Mono({ variable: "--font-jetbrains", subsets: ["latin"] });
const fira = Fira_Code({ variable: "--font-fira", subsets: ["latin"] });
const sourceCode = Source_Code_Pro({ variable: "--font-source-code", subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// Terapkan preferensi sebelum render agar tidak berkedip.
const applyPrefs = `try{var d=document.documentElement,s=localStorage,f=s.getItem("app-font"),c=s.getItem("app-codefont"),z=parseInt(s.getItem("app-codesize"),10);if(f)d.dataset.font=f;if(c)d.dataset.codefont=c;if(z>=10&&z<=28){d.dataset.codesize="1";d.style.setProperty("--code-size",z+"px")}}catch(e){}`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} ${inter.variable} ${roboto.variable} ${jakarta.variable} ${jetbrains.variable} ${fira.variable} ${sourceCode.variable}`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: applyPrefs }} />
      </head>
      <body>{children}</body>
    </html>
  );
}
